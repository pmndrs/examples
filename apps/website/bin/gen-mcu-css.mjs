// Writes the Material Design 3 palette that `app/globals.css` imports.
//
// This runs in plain node, ahead of `next dev` / `next build`, rather than
// from the layout, because `material-theme-builder`'s dist is one bundle with
// a hoisted "use client" -- calling `builder()` from a Server Component throws
// (`Attempted to call builder() from the server`). Generating here keeps the
// palette in the stylesheet, which is what makes it show up in the prerendered
// HTML: the package's own `<Mcu>` fills its <style> tag from
// `useInsertionEffect`, so with an `output: "export"` site the first paint
// would land before any of the colours exist.

import { writeFile } from "node:fs/promises";
import { builder } from "material-theme-builder";

/**
 * The one hex the whole palette hangs off -- poimandres' signature mint.
 * Every `--md-sys-color-*` role comes out of this, and `app/globals.css`
 * hands those on to shadcn's tokens.
 */
const SOURCE = "#5de4c7";

/** `scheme`, `contrast`, core-colour overrides and `customColors` go here. */
const CONFIG = { scheme: "tonalSpot" };

const out = new URL("../app/mcu.generated.css", import.meta.url);

await writeFile(
  out,
  `/* Generated by bin/gen-mcu-css.mjs -- do not edit, do not commit. */\n${builder(SOURCE, CONFIG).toCss()}`,
);
